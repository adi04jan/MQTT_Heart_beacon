"""Rev C for EAGLE without the inconsistency: copy the schematic to <name>2.sch (no board yet), and write
  - <name>_place.scr: outline (Dimension 20, Milling 46, bPlace 22), every part's position/rotation/side, the VSYS
    wire landing via, then RATSNEST, all taken from the placed <name>.brd;
  - <name>_rules.dru: that board's design rules with the maker's 0.4 mm width / 0.35 mm clearance.
In EAGLE: open <name>2.sch, Switch to board (create from schematic: yes), delete EAGLE's default outline,
File > Execute Script <name>_place.scr, then DRC > Load <name>_rules.dru. EAGLE built that board itself, so
schematic and board are consistent and the airwires show.

usage: python -I eagle_place.py <dir> <name>      e.g. ... ES32_heart ESP32_heart_revC
"""
import shutil
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

CLEAR = "0.35mm"
WIDTH = "0.4mm"


def main(d: Path, name: str) -> None:
    brd = ET.parse(d / f"{name}.brd").getroot()
    board = brd.find("drawing/board")
    out = ["# Generated by hardware/pcb/eagle_place.py from " + name + ".brd", "GRID MM;"]
    for layer in ("20", "46", "22"):
        items = [c for c in board.find("plain") if c.get("layer") == layer]
        if not items:
            continue
        out.append(f"LAYER {layer};")
        for c in items:
            assert c.tag in ("wire", "circle") and not c.get("curve"), c.attrib  # straight lines and circles only
            if c.tag == "wire":
                out.append(f"WIRE {c.get('width')} ({c.get('x1')} {c.get('y1')}) ({c.get('x2')} {c.get('y2')});")
            else:
                x, y, r = (float(c.get(k)) for k in ("x", "y", "radius"))
                out.append(f"CIRCLE {c.get('width')} ({x:g} {y:g}) ({x + r:g} {y:g});")
    for e in board.iter("element"):
        out.append(f"MOVE '{e.get('name')}' ({e.get('x')} {e.get('y')});")
        out.append(f"ROTATE ={e.get('rot') or 'R0'} '{e.get('name')}';")
    for s in board.iter("signal"):
        for v in s.iter("via"):
            out.append(f"CHANGE DRILL {v.get('drill')};")
            out.append(f"VIA '{s.get('name')}' {v.get('diameter')} ROUND ({v.get('x')} {v.get('y')});")
    out += ["RATSNEST;", "WINDOW FIT;"]
    (d / f"{name}_place.scr").write_text("\n".join(out) + "\n", encoding="ascii", newline="\r\n")

    rules = {p.get("name"): p.get("value") for p in board.find("designrules")}
    for k in ("mdWireWire", "mdWirePad", "mdWireVia", "mdPadPad", "mdPadVia", "mdViaVia",
              "mdSmdPad", "mdSmdVia", "mdSmdSmd"):
        rules[k] = CLEAR
    rules["msWidth"] = WIDTH
    lines = [f"description[en] = <b>Heart beacon {name}</b>: {WIDTH} min width, {CLEAR} clearance (CNC V-bit)"]
    lines += [f"{k} = {v}" for k, v in rules.items()]
    (d / f"{name}_rules.dru").write_text("\n".join(lines) + "\n", encoding="ascii", newline="\r\n")

    clean = d / f"{name}2.sch"
    assert not clean.exists() and not (d / f"{name}2.brd").exists(), "refusing to overwrite"
    shutil.copyfile(d / f"{name}.sch", clean)
    n_el = sum(1 for _ in board.iter("element"))
    assert sum(1 for line in out if line.startswith("MOVE")) == n_el
    print(f"{clean.name}, {name}_place.scr ({n_el} parts), {name}_rules.dru")


if __name__ == "__main__":
    main(Path(sys.argv[1]), sys.argv[2])
